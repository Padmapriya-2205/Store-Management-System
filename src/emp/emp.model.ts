import { Injectable, OnModuleInit } from '@nestjs/common';
import type { QueryResultRow } from 'pg';
import { PostgresConnection } from '../database/postgres.connection';

export interface Employee extends QueryResultRow {
  id: number;
  name: string;
  email: string;
}

export interface Product extends QueryResultRow {
  id: number;
  name: string;
}
export interface CreateEmpInput {
  name: string;
  salary: number;
  age: number;
  dept_id: number;
}

export interface UpdateEmpInput {
  name?: string;
  salary?: number;
  age?: number;
  dept_id?: number;
} 

@Injectable()
export class EmpModel implements OnModuleInit {
  constructor(private readonly postgres: PostgresConnection) {}

  async onModuleInit(): Promise<void> {
    await this.postgres.query(`
      CREATE TABLE IF NOT EXISTS employees (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL
      )
    `);
  }

  async create(input: CreateEmpInput): Promise<Employee> {
    const result = await this.postgres.query<Employee>(
      'INSERT INTO employees (name, salary, age, dept_id) VALUES ($1, $2, $3, $4) RETURNING *',
      [input.name, input.salary, input.age, input.dept_id],
    );
    return result.rows[0];
  }

  async fetchAllProductsWithCategory() {
  const result = await this.postgres.query(`
   SELECT c.name as "category_name",c.id,count(*) as "no of products"  FROM dev.products p
inner join dev.categories c on c.id= p.category_id
group by c.name,c.id;
  `);

  return result.rows;
}

  async deleteCategoriesWithNoProducts() {
  const result = await this.postgres.query(`
    WITH category_count AS (
      SELECT
        c.id,
        c.name AS category_name,
        COUNT(p.id) AS no_of_products
      FROM dev.categories c
      LEFT JOIN dev.products p
        ON c.id = p.category_id
      GROUP BY c.id, c.name
    )
    DELETE FROM dev.categories
    WHERE id IN (
      SELECT id
      FROM category_count
      WHERE no_of_products = 0
    )
    RETURNING *;
  `);

  return result.rows;
}


  async findById(id: number): Promise<Employee | undefined> {
    const result = await this.postgres.query<Employee>(
      'SELECT id, name, email FROM employees WHERE id = $1',
      [id],
    );
    return result.rows[0];
  }

  async update(
    id: number,
    input: UpdateEmpInput,
  ): Promise<Employee | undefined> {
    const result = await this.postgres.query<Employee>(
      `UPDATE employees
       SET name = COALESCE($2, name), age = COALESCE($3, age), dept_id = COALESCE($4, dept_id)
       WHERE id = $1
       RETURNING *`,
      [id, input.name ?? null, input.age ?? null, input.dept_id ?? null],
    );
    return result.rows[0];
  }

  async delete(id: number): Promise<Employee | undefined> {
    const result = await this.postgres.query<Employee>(
      'DELETE FROM employees WHERE id = $1 RETURNING id, name, email',
      [id],
    );
    return result.rows[0];
  }

  findOrdersByCustomerId(id: number) {
    return this.postgres.query(`
      select * from dev.orders
      where customer_id=$1
    `, [id]);
  }

  findPendingOrders() {
    return this.postgres.query(`
      SELECT *
FROM dev.orders
WHERE status = 'PENDING'
  AND created_at >= NOW() - INTERVAL '7 days';
    `);
  }

  findCustomerOrdersCount() {
    return this.postgres.query(`
      SELECT c.name as "customer_name",count(*) as "no_of_orders"  FROM dev.customers c
inner join dev.orders o on o.customer_id= c.id
group by o.customer_id,c.name;
    `);
  }

  findCustomerDetails(name: string) {
    console.log("name is", name);
    return this.postgres.query(`
      SELECT name,phone,email
       FROM dev.customers WHERE name = $1
    `, [name]);
  }
}
